import pandas as pd
df = pd.read_csv("/home/juliafalchi/ocrtest/work/resultados/resultados.csv")
print("linhas:", len(df), "| NaN cer:", df.cer.isna().sum())
print("\nTempo por pagina (s), mediana e media, por ferramenta:")
print(df.groupby("ferramenta").tempo_s.agg(["median", "mean", "max"]).round(1))
print("\nCER medio por ferramenta e condicao:")
print(df.pivot_table(index="condicao", columns="ferramenta", values="cer", aggfunc="mean").round(3))
print("\nWER medio por ferramenta e condicao:")
print(df.pivot_table(index="condicao", columns="ferramenta", values="wer", aggfunc="mean").round(3))
print("\nCER > 1.0 (casos):", int((df.cer > 1.0).sum()))
print(df[df.cer > 1.0].groupby(["ferramenta", "condicao"]).size())
print("\nCER == 1.0 exato (provavel saida vazia):")
print(df[(df.cer - 1.0).abs() < 1e-9].groupby(["ferramenta", "condicao"]).size())
print("\nTempo total estimado para 60 paginas (horas), pelo tempo medio por execucao:")
por_exec = df.tempo_s.mean()
print(round(por_exec, 1), "s por execucao ->", round(por_exec * 60 * 5 * 4 / 3600, 1), "h (60 pag x 5 cond x 4 ferr)")
